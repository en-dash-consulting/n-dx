/**
 * Classify each predicted conflict and offer a deterministic fix.
 *
 * Pure: it reads the merge-tree stages and conflicted result the collector
 * already has, plus the project config, and returns data. It reads no file,
 * runs no process and writes nothing; nothing here asks a model.
 *
 * Every fix assumes the merge a person would run on this branch,
 * `git merge <base>`: "ours" is this branch (merge-tree stage 3) and
 * "theirs" is the base (stage 2). A fix is either argv steps to run in order
 * from the worktree root, or a unified diff against this branch's copy of the
 * file. Source conflicts never get one.
 *
 * Classes, first match wins:
 *
 * | class              | when                                                          |
 * |--------------------|---------------------------------------------------------------|
 * | generated          | the path matches a `web.generatedFiles` glob                  |
 * | prd-state          | a v2 `state.yaml` while `merge.rex-state.driver` is unset     |
 * | duplicate-capture  | add/add on a PRD item file, same title, different ids          |
 * | prd-children-table | a v1 `prd_tree` `index.md`, every hunk inside `## Children`   |
 * | allowlist-union    | every hunk only adds lines on both sides                      |
 * | source             | everything else                                               |
 *
 * @module web/server/branch-health/conflicts
 */

import type {
  ConflictClass,
  ConflictFix,
  GeneratedFileRule,
  PredictedConflict,
  WorktreeRef,
} from "./types.js";
import { unifiedDiff } from "./unified-diff.js";

/** One conflicted file as merge-tree left it. Text is null for a missing stage or a binary blob. */
export interface ConflictSides {
  path: string;
  /** 1 = common ancestor, 2 = base, 3 = this branch. */
  stages: number[];
  ancestor: string | null;
  /** The base's version (stage 2, "theirs" when this branch merges the base). */
  base: string | null;
  /** This branch's version (stage 3, "ours"). */
  branch: string | null;
  /** The conflicted result merge-tree wrote, in diff3 style; null when there is none. */
  result: string | null;
}

/** Another local worktree and the paths its branch changed against the same base. */
export interface WorktreeChanges extends WorktreeRef {
  changed: readonly string[];
}

export interface ConflictContext {
  /** `web.generatedFiles` from the project config; empty when undeclared. */
  generatedFiles: readonly GeneratedFileRule[];
  /** Whether `merge.rex-state.driver` is set in this repository's git config. */
  rexStateDriver: boolean;
  /** The other local worktrees, for naming who else changed a source file. */
  worktrees: readonly WorktreeChanges[];
}

/** What `ndx init` registers for the rex-state driver (packages/core/gitattributes-pins.js). */
export const REX_STATE_DRIVER = { name: "n-dx PRD state merge", driver: "rex merge-state %O %A %B %P" } as const;

const REX_DIR = String.raw`(?:^|/)(?:\.rex|\.ndx/rex)/`;
const V1_INDEX = new RegExp(`${REX_DIR}prd_tree/(?:.+/)?index\\.md$`);
const V2_STATE = new RegExp(`${REX_DIR}(?:product|changes)/(?:.+/)?state\\.yaml$`);
const PRD_ITEM = new RegExp(`${REX_DIR}(?:prd_tree|product|changes)/.+\\.md$`);

/** Classify every conflict; generated files come last, since their fix regenerates over the others. */
export function classifyConflicts(conflicts: readonly ConflictSides[], ctx: ConflictContext): PredictedConflict[] {
  const classified = conflicts.map((c) => classifyConflict(c, ctx));
  return [
    ...classified.filter((c) => c.class !== "generated"),
    ...classified.filter((c) => c.class === "generated"),
  ];
}

export function classifyConflict(c: ConflictSides, ctx: ConflictContext): PredictedConflict {
  const verdict = decide(c, ctx);
  const otherWorktrees = verdict.class === "source"
    ? ctx.worktrees.filter((w) => w.changed.includes(c.path)).map(({ path, branch }) => ({ path, branch }))
    : [];
  return { path: c.path, stages: c.stages, ...verdict, otherWorktrees };
}

interface Verdict {
  class: ConflictClass;
  reason: string;
  fix: ConflictFix | null;
}

function decide(c: ConflictSides, ctx: ConflictContext): Verdict {
  const rule = ctx.generatedFiles.find((r) => r.paths.some((glob) => globToRegExp(glob).test(c.path)));
  if (rule) {
    return {
      class: "generated",
      reason: `Generated by \`${rule.command.join(" ")}\` (web.generatedFiles): take the base's copy and regenerate, after every other file is resolved.`,
      fix: { steps: [["git", "checkout", "--theirs", "--", c.path], [...rule.command], ["git", "add", "--", c.path]] },
    };
  }

  if (V2_STATE.test(c.path)) {
    if (!ctx.rexStateDriver) {
      return {
        class: "prd-state",
        reason: "PRD state merges by item id through the rex-state driver, but merge.rex-state.driver is not registered here: register it and redo this file's merge. If the driver leaves conflict markers, the check step stops before they are staged.",
        fix: {
          steps: [
            ["git", "config", "merge.rex-state.name", REX_STATE_DRIVER.name],
            ["git", "config", "merge.rex-state.driver", REX_STATE_DRIVER.driver],
            // `checkout --merge` exits 0 even when the driver could not resolve
            // a row and wrote markers; `diff --check` exits non-zero on them.
            ["git", "checkout", "--merge", "--", c.path],
            ["git", "diff", "--check", "HEAD", "--", c.path],
            ["git", "add", "--", c.path],
          ],
        },
      };
    }
    return source("The rex-state driver is registered, so this is a state conflict it could not resolve by item id.");
  }

  const duplicate = duplicateCapture(c);
  if (duplicate) return duplicate;

  const hunks = c.result === null ? null : parseConflictHunks(c.result);

  if (V1_INDEX.test(c.path)) {
    const childrenOnly = hunks && hunks.length > 0 && hunks.every((h) => h.section === "## Children" && h.tableOnly);
    // The fix keeps this branch's copy whole, so it is safe only when the base
    // changed nothing above the table that merged cleanly into the result.
    if (childrenOnly && c.branch !== null && c.result !== null && beforeChildren(c.result) !== beforeChildren(c.branch)) {
      return source("The base also changed this item above its ## Children table; keeping this branch's copy would drop that change.");
    }
    if (childrenOnly) {
      return {
        class: "prd-children-table",
        reason: "Every conflict is inside the informational ## Children table, which rex rewrites from the directory.",
        fix: {
          steps: [
            ["git", "checkout", "--ours", "--", c.path],
            ["rex", "validate", "--post-merge", "--repair"],
            ["git", "add", "--", c.path],
            ["rex", "validate"],
          ],
        },
      };
    }
    return source("A PRD index.md conflict outside its ## Children table changes the item itself.");
  }

  if (hunks && hunks.length > 0 && c.stages.includes(1) && c.branch !== null && hunks.every((h) => h.ancestor !== null && h.ancestor.length === 0)) {
    const union = unionResult(c.result!);
    return {
      class: "allowlist-union",
      reason: "Every conflict only adds lines on both sides: keep both, this branch's lines first.",
      fix: { diff: unifiedDiff(c.path, c.branch, union) },
    };
  }

  if (hunks && hunks.some((h) => h.ancestor === null)) {
    return source("The conflicted result has no ancestor section, so whether a side removed lines cannot be told.");
  }
  return source(sourceReason(c, hunks));
}

/** A v1 index.md up to its `## Children` heading: the frontmatter and anything else the item holds. */
function beforeChildren(text: string): string {
  const lines = text.split("\n");
  const at = lines.findIndex((line) => line.trim() === "## Children");
  return (at < 0 ? lines : lines.slice(0, at)).join("\n");
}

function source(reason: string): Verdict {
  return { class: "source", reason, fix: null };
}

function sourceReason(c: ConflictSides, hunks: ConflictHunk[] | null): string {
  if (!c.stages.includes(2)) return "The base deleted this file and this branch changed it.";
  if (!c.stages.includes(3)) return "This branch deleted this file and the base changed it.";
  if (!c.stages.includes(1)) return "Both sides added this file with different content.";
  if (!hunks || hunks.length === 0) return "No text conflict could be read (a binary file or a mode change).";
  return "A side removes or changes a line the other side also changed: a person decides.";
}

/** Both sides added the same PRD item under different ids: keep the base's. */
function duplicateCapture(c: ConflictSides): Verdict | null {
  if (c.stages.includes(1) || c.base === null || c.branch === null || !PRD_ITEM.test(c.path)) return null;
  const base = frontmatter(c.base);
  const branch = frontmatter(c.branch);
  if (!base.id || !branch.id || base.id === branch.id || !base.title || base.title !== branch.title) return null;
  return {
    class: "duplicate-capture",
    reason: `Both sides captured "${base.title}": the base as ${base.id}, this branch as ${branch.id}. Keep ${base.id}; taking the base's copy removes ${branch.id}, and \`rex validate --post-merge\` reports anything still pointing at it.`,
    fix: {
      steps: [
        ["git", "checkout", "--theirs", "--", c.path],
        ["git", "add", "--", c.path],
        ["rex", "validate", "--post-merge"],
      ],
    },
  };
}

/** `id` and `title` from a Markdown file's YAML frontmatter, as rex writes them. */
export function frontmatter(text: string): { id: string | null; title: string | null } {
  const match = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(text);
  const fields: { id: string | null; title: string | null } = { id: null, title: null };
  if (!match) return fields;
  for (const line of match[1].split(/\r?\n/)) {
    const field = /^(id|title):\s*(.*)$/.exec(line);
    if (field) fields[field[1] as "id" | "title"] = scalar(field[2]);
  }
  return fields;
}

function scalar(raw: string): string | null {
  const value = raw.trim();
  if (value.startsWith('"')) {
    try {
      const parsed: unknown = JSON.parse(value);
      return typeof parsed === "string" ? parsed : null;
    } catch {
      return null;
    }
  }
  if (value.startsWith("'") && value.endsWith("'") && value.length >= 2) return value.slice(1, -1).replace(/''/g, "'");
  return value || null;
}

// ---------------------------------------------------------------------------
// diff3 conflict hunks
// ---------------------------------------------------------------------------

export interface ConflictHunk {
  /** The base's lines (merge-tree's first side). */
  base: string[];
  /** The ancestor's lines; null when the result was not written in diff3 style. */
  ancestor: string[] | null;
  /** This branch's lines. */
  branch: string[];
  /** The last `#` heading above the hunk, or null. */
  section: string | null;
  /** Whether every line on every side is a Markdown table row or blank. */
  tableOnly: boolean;
}

type Segment = { kind: "text"; lines: string[] } | { kind: "hunk"; hunk: ConflictHunk };

const OPEN = /^<{7,}(?: |$)/;
const ANCESTOR = /^\|{7,}(?: |$)/;
const SPLIT = /^={7,}$/;
const CLOSE = /^>{7,}(?: |$)/;
const HEADING = /^#{1,6} /;
const TABLE_ROW = /^\s*(?:\|.*\|)?\s*$/;

function segments(result: string): Segment[] | null {
  const lines = result.split("\n");
  const out: Segment[] = [];
  let text: string[] = [];
  let section: string | null = null;
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (!OPEN.test(line)) {
      if (HEADING.test(line)) section = line.trim();
      text.push(line);
      i++;
      continue;
    }
    if (text.length) out.push({ kind: "text", lines: text });
    text = [];
    const base: string[] = [];
    let ancestor: string[] | null = null;
    const branch: string[] = [];
    let side: string[] = base;
    i++;
    for (;; i++) {
      if (i >= lines.length) return null; // an unterminated hunk: not a result we can read
      const l = lines[i];
      if (ANCESTOR.test(l) && side === base) side = ancestor = [];
      else if (SPLIT.test(l) && side !== branch) side = branch;
      else if (CLOSE.test(l) && side === branch) break;
      else side.push(l);
    }
    i++;
    const tableOnly = [...base, ...(ancestor ?? []), ...branch].every((l) => TABLE_ROW.test(l));
    out.push({ kind: "hunk", hunk: { base, ancestor, branch, section, tableOnly } });
  }
  if (text.length) out.push({ kind: "text", lines: text });
  return out;
}

/** The conflict hunks in a diff3-style result, or null when it cannot be read. */
export function parseConflictHunks(result: string): ConflictHunk[] | null {
  const segs = segments(result);
  return segs ? segs.flatMap((s) => (s.kind === "hunk" ? [s.hunk] : [])) : null;
}

/** The result with every hunk replaced by this branch's lines, then the base's. */
function unionResult(result: string): string {
  return segments(result)!
    .flatMap((s) => (s.kind === "text" ? s.lines : [...s.hunk.branch, ...s.hunk.base]))
    .join("\n");
}

/**
 * `web.generatedFiles` as declared, or undefined when it is not a list. A
 * rule without at least one glob and a non-empty argv is dropped rather than
 * guessed at.
 */
export function parseGeneratedFiles(value: unknown): GeneratedFileRule[] | undefined {
  if (!Array.isArray(value)) return undefined;
  const strings = (v: unknown): string[] | null =>
    Array.isArray(v) && v.length > 0 && v.every((s) => typeof s === "string" && s !== "") ? (v as string[]) : null;
  return value.flatMap((rule) => {
    if (!rule || typeof rule !== "object") return [];
    const paths = strings((rule as Record<string, unknown>).paths);
    const command = strings((rule as Record<string, unknown>).command);
    return paths && command ? [{ paths, command }] : [];
  });
}

// ---------------------------------------------------------------------------
// Globs
// ---------------------------------------------------------------------------

/** A repo-relative glob: `**` crosses directories, `*` and `?` do not. */
export function globToRegExp(glob: string): RegExp {
  let re = "";
  for (let i = 0; i < glob.length; i++) {
    const ch = glob[i];
    if (ch === "*" && glob[i + 1] === "*") {
      const slash = glob[i + 2] === "/";
      re += slash ? "(?:.*/)?" : ".*";
      i += slash ? 2 : 1;
    } else if (ch === "*") re += "[^/]*";
    else if (ch === "?") re += "[^/]";
    else re += ch.replace(/[.+^${}()|[\]\\]/g, "\\$&");
  }
  return new RegExp(`^${re}$`);
}
