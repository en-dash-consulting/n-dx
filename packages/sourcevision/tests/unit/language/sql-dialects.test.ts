/**
 * Dialect classification. The PetClinic goldens mirror the shape of Spring
 * PetClinic's `src/main/resources/db/<engine>/schema.sql` files: one schema
 * written for each of H2, HSQLDB, MySQL and PostgreSQL.
 */

import { describe, expect, it } from "vitest";

import {
  CONFIG_RULES,
  PATH_RULES,
  SYNTAX_RULES,
  classifySqlDialect,
  dialectEvidenceFromConfig,
} from "../../../src/language/sql-dialects.js";

const PETCLINIC: Record<string, { source: string; dialect: string; confidence: string; markers: string[] }> = {
  "src/main/resources/db/h2/schema.sql": {
    source: "CREATE TABLE vets (id INTEGER IDENTITY PRIMARY KEY, first_name VARCHAR(30));",
    dialect: "h2",
    confidence: "medium",
    markers: ["path-h2"],
  },
  "src/main/resources/db/hsqldb/schema.sql": {
    source: "CREATE TABLE vets (id INTEGER GENERATED BY DEFAULT AS IDENTITY, first_name VARCHAR(30));",
    dialect: "h2",
    confidence: "medium",
    markers: ["path-h2"],
  },
  "src/main/resources/db/mysql/schema.sql": {
    source:
      "CREATE TABLE IF NOT EXISTS vets (\n  id INT(4) UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,\n  INDEX(last_name)\n) engine=InnoDB;",
    dialect: "mysql",
    confidence: "high",
    markers: ["mysql-auto-increment", "mysql-engine", "path-mysql"],
  },
  "src/main/resources/db/postgres/schema.sql": {
    source: "CREATE TABLE IF NOT EXISTS vets (\n  id SERIAL PRIMARY KEY,\n  first_name TEXT\n);",
    dialect: "postgresql",
    confidence: "high",
    markers: ["path-postgresql", "pg-serial"],
  },
  "src/main/resources/db/postgres/data.sql": {
    source: "INSERT INTO vets (first_name) SELECT 'James' WHERE NOT EXISTS (SELECT * FROM vets);",
    dialect: "postgresql",
    confidence: "medium",
    markers: ["path-postgresql"],
  },
};

describe("PetClinic goldens", () => {
  for (const [path, golden] of Object.entries(PETCLINIC)) {
    it(path, () => {
      const result = classifySqlDialect(path, golden.source);
      expect(result.dialect).toBe(golden.dialect);
      expect(result.confidence).toBe(golden.confidence);
      expect(result.evidence.map((item) => item.ruleId).sort()).toEqual(golden.markers);
    });
  }
});

describe("syntax markers", () => {
  const classify = (source: string, path = "schema.sql") => classifySqlDialect(path, source);

  it("recognises T-SQL by GO batches, IDENTITY seeds and brackets", () => {
    const result = classify("CREATE TABLE [dbo].[owners] ([id] INT IDENTITY(1,1));\nGO\n");
    expect(result.dialect).toBe("mssql");
    expect(result.confidence).toBe("high");
    expect(result.evidence.find((item) => item.ruleId === "mssql-go-batch")?.line).toBe(2);
  });

  it("recognises Oracle by VARCHAR2", () => {
    expect(classify("CREATE TABLE owners (name VARCHAR2(30), age NUMBER(3));").dialect).toBe("oracle");
  });

  it("recognises SQLite by PRAGMA and AUTOINCREMENT", () => {
    const result = classify("PRAGMA foreign_keys = ON;\nCREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT);");
    expect(result.dialect).toBe("sqlite");
    expect(result.confidence).toBe("high");
  });

  it("ignores markers inside comments", () => {
    const result = classify("-- AUTO_INCREMENT engine=InnoDB\n/* SERIAL */\nCREATE TABLE t (id int);");
    expect(result.dialect).toBe("unknown");
    expect(result.confidence).toBe("none");
    expect(result.evidence).toEqual([]);
  });

  it("reports unknown on a tie rather than picking by name", () => {
    expect(classify("CREATE TABLE t (id int AUTO_INCREMENT);", "db/h2/x.sql").dialect).toBe("unknown");
  });

  it("lets a PostgreSQL dollar-quoted body outweigh a plain path", () => {
    const result = classify("CREATE FUNCTION f() RETURNS int AS $$ SELECT 1 $$ LANGUAGE sql;");
    expect(result.dialect).toBe("postgresql");
  });
});

describe("config evidence", () => {
  it("reads URL schemes and engine names, never hosts or credentials", () => {
    const evidence = dialectEvidenceFromConfig("url=jdbc:postgresql://db.internal:5432/app\nuser=admin\npassword=hunter2");
    expect(evidence.map((item) => item.dialect)).toEqual(["postgresql"]);
    expect(JSON.stringify(evidence)).not.toMatch(/db\.internal|admin|hunter2/);
  });

  it("breaks an otherwise unmarked file's tie", () => {
    const config = dialectEvidenceFromConfig("engine: mysql");
    expect(classifySqlDialect("migrations/001.sql", "CREATE TABLE t (id int);", config).dialect).toBe("mysql");
  });
});

describe("rule provenance", () => {
  for (const rule of [...SYNTAX_RULES, ...PATH_RULES, ...CONFIG_RULES]) {
    it(`${rule.id} records where it comes from`, () => {
      if (rule.provenance.kind === "vendor-docs") {
        expect(rule.provenance.url).toMatch(/^https:\/\//);
        expect(rule.provenance.verified).toMatch(/^\d{4}-\d{2}-\d{2}$/);
      } else {
        expect(rule.provenance.note.length).toBeGreaterThan(0);
      }
    });
  }

  it("backs every syntax rule with vendor documentation", () => {
    expect(SYNTAX_RULES.every((rule) => rule.provenance.kind === "vendor-docs")).toBe(true);
  });
});
