import { describe, it, expect, beforeEach, afterEach } from "vitest";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { goConfig, typescriptConfig } from "@n-dx/lang-kit";
import { mergeLanguageConfigs } from "../../../src/language/detect.js";
import { analyzeInventory, classifyRole } from "../../../src/analyzers/inventory.js";

const HEADER = "// Code generated by sqlc. DO NOT EDIT.\n";

const role = (path: string, head: string, config = goConfig): string =>
  classifyRole(path, path.endsWith(".go") ? "Go" : "TypeScript", config, head);

describe("Go generated-code header", () => {
  it("marks a .go file with the header as generated", () => {
    expect(role("db/queries.go", `${HEADER}\npackage db\n`)).toBe("generated");
  });

  it("accepts the header after other leading comments and with CRLF endings", () => {
    expect(role("db/q.go", `// Copyright\n\n${HEADER}\npackage db\n`)).toBe("generated");
    expect(role("db/q.go", "// Code generated by x. DO NOT EDIT.\r\npackage db\r\n")).toBe("generated");
  });

  it("ignores the phrase after the package clause", () => {
    expect(role("db/q.go", `package db\n\n${HEADER}`)).toBe("source");
  });

  it("requires the exact line shape", () => {
    expect(role("db/q.go", "// Code generated by x. DO NOT EDIT\npackage db\n")).toBe("source");
    expect(role("db/q.go", "// note: Code generated by x. DO NOT EDIT.\npackage db\n")).toBe("source");
  });

  it("ignores the phrase in a non-Go file", () => {
    expect(role("src/a.ts", `${HEADER}export {};\n`, mergeLanguageConfigs([goConfig, typescriptConfig]))).toBe("source");
  });

  it("applies in a mixed-language repo", () => {
    expect(role("db/q.go", `${HEADER}package db\n`, mergeLanguageConfigs([typescriptConfig, goConfig]))).toBe("generated");
  });

  it("leaves a test file a test", () => {
    expect(role("db/q_test.go", `${HEADER}package db\n`)).toBe("test");
  });

  it("changes nothing without a head", () => {
    expect(classifyRole("db/q.go", "Go", goConfig)).toBe("source");
  });

  it("records provenance", () => {
    const [rule] = goConfig.generatedHeaders ?? [];
    expect(rule.source).toBe("https://go.dev/s/generatedcode");
    expect(rule.verified).toMatch(/^\d{4}-\d{2}-\d{2}$/);
  });
});

describe("inventory with Go generated headers", () => {
  let dir: string;
  beforeEach(async () => {
    dir = await mkdtemp(join(tmpdir(), "sv-gogen-"));
  });
  afterEach(async () => {
    await rm(dir, { recursive: true, force: true });
  });

  it("changes only the file carrying the header", async () => {
    await writeFile(join(dir, "go.mod"), "module x\n\ngo 1.22\n");
    await writeFile(join(dir, "gen.go"), `${HEADER}\npackage x\n`);
    await writeFile(join(dir, "plain.go"), "package x\n");
    const inv = await analyzeInventory(dir);
    const roles = Object.fromEntries(inv.files.map((f) => [f.path, f.role]));
    expect(roles["gen.go"]).toBe("generated");
    expect(roles["plain.go"]).toBe("source");
  });
});
